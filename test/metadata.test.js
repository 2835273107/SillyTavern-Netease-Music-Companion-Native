import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = relative => fs.readFileSync(path.join(root, relative), 'utf8');

test('keeps manifest, package and config on the native namespace', () => {
    const manifest = JSON.parse(read('manifest.json'));
    const packageJson = JSON.parse(read('plugin/package.json'));
    const config = JSON.parse(read('plugin/config.example.json'));
    const frontend = read('index.js');
    const backend = read('plugin/index.js');
    const service = read('plugin/together-native/service.py');

    assert.equal(manifest.version, '1.12.4');
    assert.equal(manifest.homePage.endsWith('SillyTavern-Netease-Music-Companion-Native'), true);
    assert.equal(packageJson.version, '1.12.4');
    assert.match(frontend, /nmcnativePlayerLyrics/);
    assert.match(backend, /\/song-audio\/:songId/);
    assert.match(backend, /\/together\/send-message/);
    assert.match(backend, /\/together\/room-playlist/);
    assert.match(backend, /\/song-comments\/:songId/);
    assert.match(service, /\/v1\/rooms\/playlist/);
    assert.match(backend, /\/player\/playlist-tracks\/:playlistId/);
    assert.match(frontend, /nmcnativePlayerPlaylistTrack/);
    assert.match(frontend, /nmcnativePlayerPlaylistList/);
    assert.match(frontend, /nmcnativePlayerTrackList/);
    assert.match(frontend, /nmcnativeTargetPlaylistList/);
    assert.doesNotMatch(frontend, /nmcnativeUsePlaylist/);
    assert.match(frontend, /正在切换目标歌单/);
    assert.doesNotMatch(frontend, /点击歌单会立即切换为目标歌单/);
    assert.doesNotMatch(frontend, /nmcnativeSwitchAccount/);
    assert.doesNotMatch(frontend, /nmcnativePlayPlaylistTrack/);
    assert.doesNotMatch(frontend, /nmcnativePlaySelectedSong/);
    assert.match(frontend, /nmcnativePlayerSearchList/);
    assert.match(frontend, /nmcnativePlayerToggle/);
    assert.match(frontend, /renderPlayerProgress/);
    assert.match(frontend, /extractFirstJsonValue/);
    assert.match(frontend, /stripReasoningArtifacts/);
    assert.match(frontend, /禁止输出 <thinking>/);
    assert.ok(
        (frontend.match(/(?:stripReasoningArtifacts|sanitizeGeneratedText)\(/g) || []).length >= 10,
    );
    assert.match(frontend, /sanitizeGeneratedText/);
    assert.match(frontend, /truncateGeneratedText/);
    assert.match(frontend, /structured: true/);
    assert.match(frontend, /nmcnativeSecondaryAiSave/);
    assert.match(frontend, /secondary-ai\/generate/);
    assert.match(backend, /\/secondary-ai\/config/);
    assert.match(backend, /\/secondary-ai\/generate/);
    assert.match(backend, /generateWithSecondaryAi/);
    assert.match(frontend, /data-nmcnative-player-source/);
    assert.match(frontend, /characterWorldbookContext/);
    assert.doesNotMatch(frontend, /WORLDBOOK_CONTEXT_LIMIT/);
    assert.match(frontend, /TOGETHER_REPLY_CHAR_LIMIT = 60/);
    assert.match(frontend, /SPEAK_SONG_CHAR_LIMIT = 80/);
    assert.match(frontend, /SONG_COMMENT_CHAR_LIMIT = 120/);
    assert.match(frontend, /getPresetManager/);
    assert.match(frontend, /speakCurrentSongToUser/);
    assert.match(frontend, /normalizeCharacterRecommendation/);
    assert.match(frontend, /同时包含第一人称“我”和对 \{\{user\}\} 说的“你”/);
    assert.match(frontend, /nmcnativeResendTogetherReply/);
    assert.match(frontend, /resendGeneratedTogetherMessage/);
    assert.match(frontend, /getSongLyricsText/);
    assert.match(frontend, /songContextForGeneration/);
    assert.match(frontend, /\/lyric\?song_id=/);
    assert.match(frontend, /结合歌词中的具体意象/);
    assert.match(frontend, /refreshCurrentTogetherSong/);
    assert.match(frontend, /messagePollTimer/);
    assert.match(backend, /\/together\/native\/now-playing/);
    assert.match(frontend, /nmcnativeTogetherPlaylistList/);
    assert.match(frontend, /renderRoomPlaylistChoices/);
    assert.match(service, /playing\.curPlaying/);
    assert.match(service, /SERVICE_VERSION = "1\.2\.0"/);
    assert.equal(config.neteaseApi.autoStart, true);
    assert.match(backend, /ensureNeteaseApiService/);
    assert.match(backend, /stopNeteaseApiService/);
    assert.match(frontend, /neteaseApi\.managed|apiState\.managed/);
    assert.equal(fs.existsSync(path.join(root, 'plugin/netease-api-runtime/package.json')), true);
    assert.doesNotMatch(frontend, /\.scrollIntoView\(/);
    assert.match(frontend, /data-nmcnative-tab/);
    assert.match(frontend, /ToolManager\.registerFunctionTool/);
    assert.match(frontend, /characterCommentOnSong/);
    assert.match(frontend, /generateTogetherReply/);
    assert.match(frontend, /includeTogetherLyrics/);
    assert.match(frontend, /filterNewSongCandidates/);
    assert.match(frontend, /existingSongsPrompt/);
    assert.match(frontend, /create-playlist-with-tracks/);
    assert.match(frontend, /commentedSongIds/);
    assert.match(backend, /\/create-playlist-with-tracks/);
    assert.match(backend, /skipExistingCheck/);
    assert.doesNotMatch(frontend, /id="nmcnativeTogetherMessage"/);
    assert.match(frontend, /nmcnativeTogetherMessageContacts/);
    assert.match(frontend, /nmcnativeTogetherMessageHistory/);
    assert.match(frontend, /substituteParams\('\{\{char\}\}'\)/);
    assert.match(frontend, /substituteParams\('\{\{user\}\}'\)/);
    assert.match(frontend, /CHAT_CHANGED/);
    assert.match(frontend, /data-nmcnative-char-template/);
    assert.match(frontend, /\.nmcnative-chat-contact[\s\S]*?align-self: flex-end/);
    assert.match(backend, /function cleanMessageText/);
    assert.match(frontend, /messages\.join\('\\n\\n'\)/);
    assert.match(backend, /\/together\/message-contacts/);
    assert.match(backend, /\/together\/message-history\/:userId/);
    assert.match(frontend, /playNextPlayerSong/);
    assert.match(backend, /\/song-info\/:songId/);
    assert.equal(packageJson.name, 'sillytavern-netease-music-companion-native');
    assert.equal(config.togetherNative.port, 3472);
    assert.equal(config.togetherNative.autoStart, false);
    assert.equal(config.secondaryAi.enabled, false);
    assert.equal(config.secondaryAi.modules.playlist, true);
    assert.match(frontend, /\/api\/plugins\/netease-music-native/);
    assert.match(frontend, /neteaseMusicCompanionNative/);
    assert.match(frontend, /nmcnativeTogetherMode/);
    assert.match(frontend, /\/together\/native\/create/);
    assert.match(backend, /id: 'netease-music-native'/);
    assert.match(backend, /togetherNative/);
    assert.doesNotMatch(backend, /id: 'netease-music'/);
});
