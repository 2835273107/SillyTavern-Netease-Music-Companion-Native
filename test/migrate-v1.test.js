import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const migrationScript = path.join(projectRoot, 'scripts', 'migrate-v1.mjs');

function createSillyTavernFixture(t) {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'nmcnative-migrate-'));
    t.after(() => fs.rmSync(root, { recursive: true, force: true }));
    fs.writeFileSync(path.join(root, 'config.yaml'), 'enableServerPlugins: true\n');
    const v1Directory = path.join(root, 'plugins', 'netease-music-companion');
    fs.mkdirSync(v1Directory, { recursive: true });
    const v1Config = {
        api_base: 'http://localhost:3000',
        accounts: {
            role: {
                music_u: 'dummy-music-u',
                csrf: 'dummy-csrf',
                label: '角色账号',
                nickname: '',
                userId: '',
                currentPlaylist: { id: '1', name: '测试歌单' },
            },
        },
        activeAccountId: 'role',
        user_netease_id: '123',
        enableTogetherListen: true,
        togetherPoc: {
            autoStart: true,
            projectPath: 'D:\\custom-poc',
            pythonPath: 'python',
            appPath: '',
            debugPort: 9222,
            port: 3456,
            remoteUrl: '',
            remoteToken: '',
        },
    };
    fs.writeFileSync(
        path.join(v1Directory, 'config.json'),
        `${JSON.stringify(v1Config, null, 2)}\n`,
    );
    return { root, v1Config, v1ConfigPath: path.join(v1Directory, 'config.json') };
}

test('migrates v1 data without modifying v1 and isolates the native POC port', t => {
    const fixture = createSillyTavernFixture(t);
    const result = spawnSync(process.execPath, [migrationScript, fixture.root], {
        encoding: 'utf8',
    });
    assert.equal(result.status, 0, result.stderr);

    const targetPath = path.join(
        fixture.root,
        'plugins',
        'netease-music-companion-native',
        'config.json',
    );
    const migrated = JSON.parse(fs.readFileSync(targetPath, 'utf8'));
    assert.equal(migrated.activeAccountId, 'role');
    assert.equal(migrated.accounts.role.music_u, 'dummy-music-u');
    assert.equal(migrated.togetherNative.port, 3472);
    assert.equal(migrated.togetherNative.autoStart, false);
    assert.deepEqual(
        JSON.parse(fs.readFileSync(fixture.v1ConfigPath, 'utf8')),
        fixture.v1Config,
    );
});

test('refuses to overwrite an existing native config without force', t => {
    const fixture = createSillyTavernFixture(t);
    const targetDirectory = path.join(fixture.root, 'plugins', 'netease-music-companion-native');
    fs.mkdirSync(targetDirectory, { recursive: true });
    fs.writeFileSync(path.join(targetDirectory, 'config.json'), '{"keep":true}\n');

    const result = spawnSync(process.execPath, [migrationScript, fixture.root], {
        encoding: 'utf8',
    });
    assert.equal(result.status, 1);
    assert.equal(
        fs.readFileSync(path.join(targetDirectory, 'config.json'), 'utf8'),
        '{"keep":true}\n',
    );
});

test('replaces the blank config generated by a fresh Native installation', t => {
    const fixture = createSillyTavernFixture(t);
    const targetDirectory = path.join(fixture.root, 'plugins', 'netease-music-companion-native');
    fs.mkdirSync(targetDirectory, { recursive: true });
    fs.copyFileSync(
        path.join(projectRoot, 'plugin', 'config.example.json'),
        path.join(targetDirectory, 'config.json'),
    );

    const result = spawnSync(process.execPath, [migrationScript, fixture.root], {
        encoding: 'utf8',
    });
    assert.equal(result.status, 0, result.stderr);
    const migrated = JSON.parse(
        fs.readFileSync(path.join(targetDirectory, 'config.json'), 'utf8'),
    );
    assert.equal(migrated.activeAccountId, 'role');
    assert.equal(migrated.togetherNative.port, 3472);
});

test('does not retain a v1 POC project path', t => {
    const fixture = createSillyTavernFixture(t);
    const v1Config = {
        ...fixture.v1Config,
        togetherPoc: {
            ...fixture.v1Config.togetherPoc,
            projectPath: path.join(
                fixture.root,
                'plugins',
                'netease-music-companion',
                'together-poc',
            ),
        },
    };
    fs.writeFileSync(fixture.v1ConfigPath, `${JSON.stringify(v1Config, null, 2)}\n`);

    const result = spawnSync(process.execPath, [migrationScript, fixture.root], {
        encoding: 'utf8',
    });
    assert.equal(result.status, 0, result.stderr);
    const migrated = JSON.parse(fs.readFileSync(path.join(
        fixture.root,
        'plugins',
        'netease-music-companion-native',
        'config.json',
    ), 'utf8'));
    assert.equal(migrated.togetherNative.port, 3472);
    assert.equal('projectPath' in migrated.togetherNative, false);
});
